/* ==========================================================
   دیوان — اتصال به مینی‌اپ تلگرام
   این فایل فقط یک کار می‌کند: به تلگرام می‌گوید صفحه آماده است
   و رنگ نوار بالا و پس‌زمینه را با تم بورگوندی هماهنگ می‌کند.
   ========================================================== */

(function () {
  "use strict";

  // همان رنگ --burgundy-deep در style.css
  var BRAND_COLOR = "#4E0612";

  // اگر صفحه بیرون از تلگرام (مثلاً در مرورگر) باز شود،
  // window.Telegram.WebApp ساخته می‌شود ولی initData خالی است.
  // با این شرط، کد در هر دو حالت بدون خطا اجرا می‌شود.
  var tg = window.Telegram && window.Telegram.WebApp;
  if (!tg) {
    return;
  }

  // ۱) به تلگرام اعلام می‌کنیم صفحه بارگذاری شده است.
  //    تا این فراخوانی نشود، تلگرام ممکن است لودینگ را نشان دهد.
  tg.ready();

  // ۲) پنجره را تا بالاترین ارتفاع ممکن باز می‌کنیم.
  tg.expand();

  // ۳) هماهنگ‌کردن رنگ‌ها تا بین نوار تلگرام و صفحه خط سفید دیده نشود.
  //    هر قابلیت از یک نسخه‌ی مشخص به بعد وجود دارد؛ نسخه را چک می‌کنیم
  //    تا در تلگرام‌های قدیمی خطا یا هشدار نگیریم.
  try {
    if (tg.isVersionAtLeast("6.1")) {
      tg.setBackgroundColor(BRAND_COLOR);
    }
    if (tg.isVersionAtLeast("6.9")) {
      // رنگ هگزادسیمال برای نوار بالا از نسخه‌ی ۶.۹ پشتیبانی می‌شود
      tg.setHeaderColor(BRAND_COLOR);
    }
    if (tg.isVersionAtLeast("7.10")) {
      // نوار پایین (در گوشی‌هایی که دارند) از نسخه‌ی ۷.۱۰
      tg.setBottomBarColor(BRAND_COLOR);
    }
  } catch (err) {
    // رنگ‌دهی تزئینی است؛ اگر نشد، برنامه نباید از کار بیفتد.
    console.warn("Telegram color setup skipped:", err);
  }
})();
